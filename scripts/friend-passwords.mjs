// Generate once locally; only hashes enter source control. --show prints the
// private handout for sharing. The existing three users keep their env passwords.
import { randomBytes, createHash } from "node:crypto";
import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const handout = new URL(".local/friend-initial-passwords.json", root);
const config = new URL("app/config/user-profiles.ts", root);
if (process.argv.includes("--show")) {
  const rows = JSON.parse(await readFile(handout, "utf8"));
  for (const row of rows) console.log(`${row.name}: ${row.password}`);
} else if (process.argv.includes("--generate")) {
  const exists = await access(handout).then(
    () => true,
    () => false,
  );
  if (exists)
    throw new Error(
      "Initial passwords already exist. Use --show; no passwords changed.",
    );
  const source = await readFile(config, "utf8");
  const marker =
    /(\/\/ GENERATED_PASSWORD_HASHES_START\n)[\s\S]*?(\s*\/\/ GENERATED_PASSWORD_HASHES_END)/;
  const normalized = source.replace(/\r\n/g, "\n");
  const match = normalized.match(marker);
  if (!match || /[a-f0-9]{64}/.test(match[0]))
    throw new Error(
      "Existing defaults cannot be regenerated by this helper. Recover the private handout or use env overrides.",
    );
  const rows = [
    ["qikai", "琦凯"],
    ["biaozi", "镖子"],
    ["jc", "jc"],
    ["ziwei", "子维"],
  ].map(([id, name]) => ({
    id,
    name,
    password: randomBytes(18).toString("base64url"),
  }));
  const hashes = rows
    .map(
      ({ id, password }) =>
        `  ${id}: "${createHash("sha256").update(password).digest("hex")}",`,
    )
    .join("\n");
  await mkdir(new URL(".local/", root), { recursive: true });
  await writeFile(handout, JSON.stringify(rows, null, 2) + "\n", {
    flag: "wx",
    mode: 0o600,
  });
  await writeFile(
    config,
    normalized.replace(
      marker,
      `$1${hashes}\n  // GENERATED_PASSWORD_HASHES_END`,
    ),
  );
  console.log(
    `Generated four passwords. Private handout: ${fileURLToPath(handout)}`,
  );
} else {
  console.log(
    "Usage: node scripts/friend-passwords.mjs --show (local handout) or --generate (first setup only)",
  );
}
